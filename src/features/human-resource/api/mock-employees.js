let employeeRows = INITIAL_EMPLOYEE_ROWS.map((row) => ({ ...row }));

let nextEmployeeId =
  Math.max(...INITIAL_EMPLOYEE_ROWS.map((row) => Number(row.id)), 0) + 1;

export function getEmployeeRows() {
  return employeeRows;
}

export function getEmployeeById(id) {
  return employeeRows.find((row) => row.id === id) ?? null;
}

export function createEmployeeRow(employeePayload) {
  const id = String(nextEmployeeId++);

  const row = {
    id,
    status: 'active',
    certificates: [],
    documents: [],
    skills: [],
    relationships: [],
    ...employeePayload,
  };

  employeeRows = [row, ...employeeRows];

  return row;
}

export function updateEmployeeRow(id, updates) {
  const index = employeeRows.findIndex((row) => row.id === id);
  if (index === -1) {
    return null;
  }

  employeeRows = [
    ...employeeRows.slice(0, index),
    { ...employeeRows[index], ...updates },
    ...employeeRows.slice(index + 1),
  ];

  return employeeRows[index];
}

export function saveEmployeeSection(id, section, data) {
  return updateEmployeeRow(id, { [section]: JSON.parse(JSON.stringify(data)) });
}

export function deleteEmployeeRow(id) {
  const index = employeeRows.findIndex((row) => row.id === id);
  if (index === -1) {
    return false;
  }

  employeeRows = employeeRows.filter((row) => row.id !== id);
  return true;
}

export function getEmployeeDisplayName(employee) {
  return [employee?.firstName, employee?.middleName, employee?.lastName]
    .filter(Boolean)
    .join(' ')
    .trim();
}

export function toggleEmployeeActive(id) {
  const index = employeeRows.findIndex((row) => row.id === id);
  if (index === -1) return null;
  const current = employeeRows[index];
  const nextActive = !current.isActive;
  const updated = {
    ...current,
    isActive: nextActive,
    status: nextActive ? 'active' : 'inactive',
  };
  employeeRows = [
    ...employeeRows.slice(0, index),
    updated,
    ...employeeRows.slice(index + 1),
  ];
  return updated;
}


export function changeDepartmentForEmployee(id, patch) {
  return updateEmployeeRow(id, patch);
}


let receptionistRows = [];
let nextReceptionistId = 1;

export function getReceptionistRows() {
  return receptionistRows;
}

export function createReceptionistRow(payload) {
  const id = String(nextReceptionistId++);
  const row = { id, receptionistId: id, ...payload };
  receptionistRows = [row, ...receptionistRows];
  return row;
}

export function updateReceptionistRow(id, payload) {
  receptionistRows = receptionistRows.map((r) =>
    r.id === id ? { ...r, ...payload } : r,
  );
  return receptionistRows.find((r) => r.id === id) ?? null;
}

export function deleteReceptionistRow(id) {
  receptionistRows = receptionistRows.filter((r) => r.id !== id);
}
